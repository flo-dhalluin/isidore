"""HTTP client used by the scheduler to ask isidore to spawn a task."""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

import httpx


class IsidoreError(RuntimeError):
    pass


class IsidoreClient:
    def __init__(
        self,
        base_url: str,
        *,
        token: str | None = None,
        timeout: float = 15.0,
        token_file: str | None = None,
    ) -> None:
        self.base_url = base_url.rstrip("/")
        self.token = token
        # When no token is shared via the environment, read the admin token from
        # this file (the shared isidore-admin volume) on every request, so a
        # token regenerated by isidore at startup is picked up without a restart.
        self.token_file = token_file or os.environ.get("SCHEDULER_ISIDORE_TOKEN_FILE") or None
        self._client = httpx.AsyncClient(timeout=timeout)

    def _effective_token(self) -> str | None:
        if self.token:
            return self.token
        if self.token_file:
            try:
                return Path(self.token_file).read_text().strip() or None
            except OSError:
                return None
        return None

    def _headers(self) -> dict[str, str]:
        token = self._effective_token()
        return {"Authorization": f"Bearer {token}"} if token else {}

    async def create_task(self, prompt: str, **kwargs: Any) -> dict[str, Any]:
        payload: dict[str, Any] = {"prompt": prompt, "origin": kwargs.pop("origin", "scheduler")}
        for key in ("model", "schedule_id"):
            value = kwargs.pop(key, None)
            if value:
                payload[key] = value
        try:
            response = await self._client.post(
                f"{self.base_url}/api/tasks", json=payload, headers=self._headers()
            )
        except httpx.HTTPError as exc:
            raise IsidoreError(f"isidore unreachable: {exc}") from exc
        if response.status_code >= 400:
            detail = response.text.strip() or response.reason_phrase
            raise IsidoreError(f"isidore returned {response.status_code}: {detail}")
        return response.json()

    async def whoami(self, task_token: str) -> dict[str, Any] | None:
        """Validate a task token against isidore's /api/auth/whoami.

        Returns the scope dict (``{task_id, root_id, origin}``) for a valid task
        token, or None on 401/any error (including isidore being unreachable) so
        callers fail closed. Never trust a self-asserted header.
        """
        try:
            response = await self._client.get(
                f"{self.base_url}/api/auth/whoami",
                headers={"Authorization": f"Bearer {task_token}"},
            )
        except httpx.HTTPError:
            return None
        if response.status_code != 200:
            return None
        try:
            data = response.json()
        except ValueError:
            return None
        return data if isinstance(data, dict) else None

    async def aclose(self) -> None:
        await self._client.aclose()
